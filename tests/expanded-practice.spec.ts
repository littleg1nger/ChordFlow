import {test,expect} from '@playwright/test'

test('卡农跟练样例、加花逐步查看与保存刷新恢复',async({page},info)=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  await page.goto('/')
  await page.getByRole('navigation').getByRole('button',{name:/和弦进行/}).click()
  await page.locator('.lesson-library summary').click()
  await page.getByRole('button',{name:/卡农 · 流动分解与回转/}).click()
  await expect(page.getByLabel('经典和弦进行',{exact:true})).toHaveValue('canon')
  await expect(page.getByLabel('进行主音',{exact:true})).toHaveValue('D')
  await expect(page.locator('.progression-chord')).toHaveCount(8)
  await expect(page.locator('.progression-chords')).toContainText('F#m')
  await expect(page.getByLabel('进行加花',{exact:true})).toHaveValue('chord-turn')
  await expect(page.getByRole('button',{name:/^八分上行分解/})).toHaveAttribute('aria-pressed','true')
  await page.locator('.event-step').last().click()
  await expect(page.locator('.event-step.selected')).toContainText('4 a')
  await expect(page.locator('.event-step.selected [data-fill=true]')).toContainText('加花 · 和弦音')
  await expect(page.locator('.source-status')).toContainText('采样钢琴')
  await page.getByLabel('练习名称',{exact:true}).fill('卡农回转练习')
  await page.getByRole('button',{name:'保存到我的练习',exact:true}).click()
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('chordflow:v1')!).exercises[0].config)
  expect(saved).toMatchObject({fill:'chord-turn',progression:'canon',pattern:'ascending',tonic:'D'})
  await page.reload()
  await page.getByRole('navigation').getByRole('button',{name:/我的练习/}).click()
  await page.getByRole('button',{name:'打开练习 卡农回转练习',exact:true}).click()
  await expect(page.getByLabel('进行加花',{exact:true})).toHaveValue('chord-turn')
  await page.getByRole('button',{name:'播放练习',exact:true}).click()
  await expect(page.getByLabel('节拍播放头',{exact:true})).toHaveAttribute('data-status','playing')
  await page.getByRole('button',{name:'停止',exact:true}).click()
  await expect(page.getByLabel('节拍播放头',{exact:true})).toHaveAttribute('data-tick','0')
  await page.locator('main').evaluate(el=>{el.scrollTop=0})
  await page.screenshot({path:info.outputPath('canon.png'),fullPage:true})
  expect(errors).toEqual([])
})

test('4536251真实移调、经过音、低音连接与七和弦分解',async({page},info)=>{
  await page.goto('/')
  await page.getByRole('navigation').getByRole('button',{name:/和弦进行/}).click()
  await page.getByLabel('经典和弦进行',{exact:true}).selectOption('4536251')
  await expect(page.locator('.progression-chord strong')).toHaveText(['F','G','Em','Am','Dm','G','C'])
  await page.getByLabel('进行主音',{exact:true}).selectOption('D')
  await expect(page.locator('.progression-chord strong')).toHaveText(['G','A','F#m','Bm','Em','A','D'])
  await page.getByLabel('进行加花',{exact:true}).selectOption('scale-approach')
  await expect(page.locator('[data-fill=true]')).toHaveCount(2)
  await expect(page.locator('[data-fill=true]').filter({hasText:'经过音'})).not.toHaveCount(0)
  await page.getByLabel('进行加花',{exact:true}).selectOption('bass-walk')
  await expect(page.locator('[data-fill=true]').first()).toContainText('左')
  await page.getByRole('button',{name:/三拍子伴奏/}).click()
  await expect(page.getByLabel('进行加花',{exact:true})).toHaveValue('none')
  await expect(page.locator('select[aria-label="进行加花"] option[value="scale-approach"]')).toHaveJSProperty('disabled',true)
  await page.locator('.lesson-library summary').click()
  await page.getByRole('button',{name:/ii–V–I · 七音分解/}).click()
  await expect(page.getByRole('button',{name:/^四音和弦分解/})).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('.event-steps')).toContainText('C5')
  await page.getByLabel('进行主音',{exact:true}).selectOption('F#')
  await expect(page.locator('.progression-chords')).toContainText('C#7')
  await expect(page.locator('.event-steps')).toContainText('F#')
  expect(await page.locator('main').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  await page.getByTestId('piano').scrollIntoViewIfNeeded()
  await page.screenshot({path:info.outputPath('decorated-piano.png'),fullPage:true})
})
