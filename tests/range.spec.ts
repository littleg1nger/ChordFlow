import {test,expect} from '@playwright/test'

test('自动音区跟随转位和演奏配置，手动选择保持并可恢复',async({page})=>{
  await page.goto('/')
  const piano=page.getByTestId('piano')
  const range=page.getByLabel('键盘起始音区',{exact:true})
  await expect(range).toHaveValue('auto')
  await expect(piano).toHaveAttribute('data-range-start','36')
  await page.getByRole('button',{name:'第一转位',exact:true}).click()
  await expect(piano).toHaveAttribute('data-range-start','48')
  await expect(piano.locator('[data-midi="72"]')).toBeAttached()
  await range.selectOption('4')
  await page.getByLabel('搜索和弦',{exact:true}).fill('F#maj7')
  await page.getByRole('button',{name:'查找和弦',exact:true}).click()
  await expect(range).toHaveValue('4')
  await expect(piano).toHaveAttribute('data-range-start','60')
  await page.reload()
  await expect(range).toHaveValue('4')
  await page.getByRole('button',{name:'恢复自动音区',exact:true}).click()
  await expect(range).toHaveValue('auto')
  await expect(piano).toHaveAttribute('data-range-start','48')
  await expect(piano.locator('[data-midi="77"]')).toBeAttached()
  await page.getByRole('navigation').getByRole('button',{name:/伴奏音型/}).click()
  await page.getByRole('button',{name:/柱式伴奏/}).click()
  await page.getByLabel('演奏音区',{exact:true}).selectOption('1')
  await expect(piano).toHaveAttribute('data-range-start','60')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.locator('.extended-patterns summary').click()
  await page.getByRole('button',{name:/^四音和弦分解/}).click()
  await page.getByRole('navigation').getByRole('button',{name:/和弦探索/}).click()
  await page.getByLabel('根音',{exact:true}).selectOption('C')
  await page.getByLabel('和弦类型',{exact:true}).selectOption('major')
  await page.getByRole('navigation').getByRole('button',{name:/和弦进行/}).click()
  await page.getByLabel('进行主音',{exact:true}).selectOption('F#')
  await expect(page.getByRole('alert')).toContainText('不适用')
  await expect(piano).toHaveAttribute('data-range-end','96')
  await expect(piano.locator('[data-midi="85"]')).toBeAttached()
})
test('手机自动横向定位到按音，手动拖动不会被播放头抢回',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await page.getByLabel('搜索和弦',{exact:true}).fill('G#m7')
  await page.getByRole('button',{name:'查找和弦',exact:true}).click()
  const piano=page.getByTestId('piano')
  await expect.poll(()=>piano.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0)
  const fit=await piano.evaluate(el=>{
    const rect=el.getBoundingClientRect()
    return [44,56,59,63,66].every(midi=>{
      const key=el.querySelector(`[data-midi="${midi}"]`)!.getBoundingClientRect()
      return key.left>=rect.left-1&&key.right<=rect.right+1
    })
  })
  expect(fit).toBe(true)
  await page.getByRole('navigation').getByRole('button',{name:/伴奏音型/}).click()
  await page.getByRole('button',{name:/柱式伴奏/}).click()
  await page.getByRole('button',{name:'播放练习',exact:true}).click()
  await expect(page.getByLabel('节拍播放头',{exact:true})).toHaveAttribute('data-status','playing')
  await piano.evaluate(el=>{el.scrollLeft=0})
  await expect.poll(()=>page.getByLabel('节拍播放头',{exact:true}).getAttribute('data-tick')).not.toBe('0')
  expect(await piano.evaluate(el=>el.scrollLeft)).toBe(0)
})
