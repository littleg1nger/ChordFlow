import { test, expect } from '@playwright/test'

test('分解音型播放、暂停继续、停止、参数切换和七和弦兼容', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /伴奏音型/ }).click()
  await expect(page.locator('.event-steps')).toContainText('C4')
  await page.getByLabel('速度 BPM', { exact: true }).fill('120')
  await page.getByLabel('循环次数', { exact: true }).selectOption('1')
  await page.getByRole('button', { name: '播放练习', exact: true }).click()
  const track = page.getByLabel('节拍播放头', { exact: true })
  await expect(track).toHaveAttribute('data-status','playing')
  await expect.poll(async () => Number(await track.getAttribute('data-tick'))).toBeGreaterThan(180)
  await page.getByRole('button', { name: '暂停练习', exact: true }).click()
  const paused = await track.getAttribute('data-tick')
  await page.waitForTimeout(250)
  await expect(track).toHaveAttribute('data-tick',paused!)
  await page.getByRole('button', { name: '继续练习', exact: true }).click()
  await expect.poll(async () => Number(await track.getAttribute('data-tick'))).toBeGreaterThan(Number(paused)+100)
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await expect(track).toHaveAttribute('data-tick','0')
  await page.getByRole('button', { name: '下一步 →', exact: true }).click()
  await expect(track).toHaveAttribute('data-tick','240')
  await expect(page.locator('.event-step.selected')).toContainText('E4')
  await page.getByLabel('音型和弦根音').selectOption('G')
  await page.getByLabel('音型和弦类型').selectOption('seven')
  await expect(page.getByRole('alert')).toContainText('不适用')
  await expect(page.getByRole('button',{name:'播放练习',exact:true})).toBeDisabled()
  await page.getByRole('button', { name: /柱式伴奏/ }).click()
  await expect(page.locator('.event-steps')).toContainText('F4')
  await page.getByRole('button',{name:'播放练习',exact:true}).click()
  await page.getByRole('button', { name: /和弦探索/ }).click()
  await expect(page.getByRole('button', { name: '试听当前和弦', exact: true })).toBeVisible()
})
