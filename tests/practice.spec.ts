import { readFile } from 'node:fs/promises'
import { test, expect } from '@playwright/test'

test('跨天并关闭页面重开后保留练习和累计时长',async ({page,context}) => {
  await page.clock.setFixedTime(new Date('2026-10-18T23:58:00+08:00'))
  await page.goto('/')
  await page.getByRole('navigation').getByRole('button',{name:'和弦进行',exact:true}).click()
  await page.getByLabel('练习名称',{exact:true}).fill('跨天保存验证')
  await page.getByRole('button',{name:'保存到我的练习',exact:true}).click()
  await page.getByRole('button',{name:'播放练习',exact:true}).click()
  await expect.poll(async()=>page.evaluate(()=>JSON.parse(localStorage.getItem('chordflow:v1')!).stats.seconds)).toBeGreaterThan(1)
  await page.getByRole('button',{name:'停止',exact:true}).click()
  const before=await page.evaluate(()=>localStorage.getItem('chordflow:v1'))
  await page.close()
  const next=await context.newPage()
  await next.clock.setFixedTime(new Date('2026-10-19T09:00:00+08:00'))
  await next.goto('/')
  await next.getByRole('navigation').getByRole('button',{name:'我的练习',exact:true}).click()
  await expect(next.getByRole('heading',{name:'跨天保存验证',exact:true})).toBeVisible()
  expect(await next.evaluate(()=>localStorage.getItem('chordflow:v1'))).toBe(before)
  await expect(next.locator('.completion-count strong')).toHaveText(String(JSON.parse(before!).stats.completions))
})

test('进行真实移调、保存刷新、完成记录及备份往返', async ({ page },testInfo) => {
  const errors: string[]=[]
  page.on('pageerror',e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button',{name:'收藏和弦',exact:true}).click()
  await page.getByRole('button',{name:/和弦进行/}).click()
  await expect(page.locator('.progression-chords')).toContainText('Am')
  await page.getByLabel('进行主音',{exact:true}).selectOption('D')
  await expect(page.locator('.progression-chords')).toContainText('Bm')
  await expect(page.locator('.event-step').first()).toContainText('D4')
  await page.getByLabel('速度 BPM',{exact:true}).fill('160')
  await page.getByLabel('循环次数',{exact:true}).selectOption('1')
  await page.getByLabel('练习名称',{exact:true}).fill('D 调慢练')
  await page.getByRole('button',{name:'保存到我的练习',exact:true}).click()
  await page.getByRole('button',{name:'播放练习',exact:true}).click()
  await expect(page.getByLabel('节拍播放头',{exact:true})).toHaveAttribute('data-status','finished',{timeout:12000})
  const stats=await page.evaluate(() => JSON.parse(localStorage.getItem('chordflow:v1')!).stats as {seconds:number;completions:number})
  expect(stats.seconds).toBeCloseTo(6,1)
  expect(stats.completions).toBe(1)
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:/我的练习/}).click()
  await expect(page.getByRole('heading',{name:'D 调慢练',exact:true})).toBeVisible()
  await page.reload()
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:/我的练习/}).click()
  await expect(page.locator('.saved-exercises')).toContainText('D – A – Bm – G')
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出 JSON 备份',exact:true}).click()
  const download=await downloadPromise
  const backup=await readFile((await download.path())!,'utf8')
  expect(JSON.parse(backup).favorites).toEqual(['C'])
  await page.getByRole('button',{name:'复制练习 D 调慢练',exact:true}).click()
  await expect(page.locator('.saved-exercise')).toHaveCount(2)
  await page.getByRole('button',{name:'删除练习 D 调慢练',exact:true}).click()
  await expect(page.locator('.saved-exercise')).toHaveCount(1)
  await page.getByLabel('选择 JSON 备份',{exact:true}).setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(backup)})
  await expect(page.locator('.import-preview')).toContainText('1 个练习、1 个收藏')
  await page.getByRole('button',{name:'替换本地数据',exact:true}).click()
  await expect(page.getByRole('heading',{name:'D 调慢练',exact:true})).toBeVisible()
  await expect(page.locator('.saved-exercise')).toHaveCount(1)
  await page.getByLabel('选择 JSON 备份',{exact:true}).setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"version":9}')})
  await expect(page.getByRole('alert')).toContainText('当前数据没有改变')
  await page.getByRole('button',{name:'打开练习 D 调慢练',exact:true}).click()
  await expect(page.getByLabel('进行主音',{exact:true})).toHaveValue('D')
  await expect(page.getByLabel('速度 BPM',{exact:true})).toHaveValue('160')
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({path:testInfo.outputPath('progression.png'),fullPage:true})
})

test('小调移调保留调式，七和弦禁用三音模板',async ({page}) => {
  await page.goto('/')
  await page.getByRole('button',{name:/和弦进行/}).click()
  await page.getByLabel('经典和弦进行',{exact:true}).selectOption('minor')
  await expect(page.locator('.mode-tag')).toHaveText('A 自然小调')
  await page.getByLabel('进行主音',{exact:true}).selectOption('B')
  await expect(page.locator('.progression-chords')).toContainText('Bm')
  await expect(page.locator('.mode-tag')).toHaveText('B 自然小调')
  await page.getByLabel('经典和弦进行',{exact:true}).selectOption('jazz')
  await expect(page.getByRole('button',{name:/Alberti 低音/})).toBeDisabled()
  await expect(page.getByRole('button',{name:'保存到我的练习',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:/柱式伴奏/}).click()
  await expect(page.getByRole('button',{name:'保存到我的练习',exact:true})).toBeEnabled()
  await expect(page.locator('.voicing-summary')).toContainText('D4 · F4 · A4 · C5')
})
